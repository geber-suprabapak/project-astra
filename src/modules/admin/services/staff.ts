import { AppError } from '../../../lib/errors/app-error.js'
import type {
  AppProviders,
  IdentityRole,
  ProfileLifecycleStatus,
} from '../../../providers/types.js'
import type { EffectivePermissionsResponse, StaffResponse } from '../schema.js'
import { assertAdminAccess } from './shared.js'

async function assertRolesExistAndActive(
  providers: AppProviders,
  roleNames: string[],
): Promise<void> {
  for (const roleName of roleNames) {
    const role = await providers.domainStore.getRoleByName(roleName)
    if (!role || !role.is_active) {
      throw AppError.validationError(`Role "${roleName}" does not exist or is inactive.`)
    }
  }
}

export async function listStaff(params: {
  actorRole: IdentityRole | null
  providers: AppProviders
}): Promise<StaffResponse[]> {
  assertAdminAccess(params.actorRole)

  const profiles = await params.providers.domainStore.getStaffProfiles()
  const results: StaffResponse[] = []

  for (const p of profiles) {
    const roles = await params.providers.domainStore.getUserRoles(p.user_id)
    const effectivePermissions = await params.providers.domainStore.getUserEffectivePermissions(
      p.user_id,
    )
    results.push({
      ...p,
      roles,
      effective_permissions: effectivePermissions,
    })
  }

  return results
}

export async function getStaff(params: {
  userId: string
  actorRole: IdentityRole | null
  providers: AppProviders
}): Promise<StaffResponse> {
  assertAdminAccess(params.actorRole)

  const profile = await params.providers.domainStore.getStaffProfile(params.userId)
  if (!profile) {
    throw AppError.notFound('Staff profile')
  }

  const roles = await params.providers.domainStore.getUserRoles(params.userId)
  const effectivePermissions = await params.providers.domainStore.getUserEffectivePermissions(
    params.userId,
  )

  return {
    ...profile,
    roles,
    effective_permissions: effectivePermissions,
  }
}

export async function createStaff(params: {
  userId?: string
  email: string
  fullName: string
  role: string
  roles?: string[]
  gender?: string | null
  password?: string
  actorId: string
  actorRole: IdentityRole | null
  providers: AppProviders
}): Promise<StaffResponse> {
  assertAdminAccess(params.actorRole)

  if (params.actorRole === 'school_admin') {
    if (params.role === 'platform_admin' || params.roles?.includes('platform_admin')) {
      throw AppError.forbidden()
    }
  }

  await assertRolesExistAndActive(params.providers, [params.role, ...(params.roles ?? [])])

  if (!params.providers.identityProvider.assignRoles) {
    throw AppError.internal('Identity provider role assignment is not configured.')
  }
  if (params.userId && params.providers.identityProvider.createStaffIdentity) {
    throw AppError.validationError('Staff identity must be generated by the identity provider.')
  }

  let identityUserId = params.userId
  if (params.providers.identityProvider.createStaffIdentity) {
    const identity = await params.providers.identityProvider.createStaffIdentity({
      email: params.email,
      fullName: params.fullName,
      role: params.role,
      password: params.password,
    })
    identityUserId = identityUserId ?? identity.userId
  }

  if (!identityUserId) {
    throw AppError.internal('Staff identity is required.')
  }
  await params.providers.identityProvider.assignRoles(identityUserId, [
    ...new Set([params.role, ...(params.roles ?? [])]),
  ])

  const profile = await params.providers.domainStore.createStaffProfile({
    userId: identityUserId,
    fullName: params.fullName,
    email: params.email,
    role: params.role,
    roles: params.roles,
    gender: params.gender,
  })

  await params.providers.domainStore.insertAuditLog({
    actor_id: params.actorId,
    action: 'create_staff',
    entity_type: 'profile',
    entity_id: profile.user_id,
    details: {
      user_id: profile.user_id,
      email: profile.email,
      full_name: profile.full_name,
      role: profile.role,
      roles: params.roles,
    },
  })

  const roles = await params.providers.domainStore.getUserRoles(profile.user_id)
  const effectivePermissions = await params.providers.domainStore.getUserEffectivePermissions(
    profile.user_id,
  )

  return {
    ...profile,
    roles,
    effective_permissions: effectivePermissions,
  }
}

export async function updateStaff(params: {
  userId: string
  fullName?: string | null
  role?: string
  roles?: string[]
  lifecycleStatus?: ProfileLifecycleStatus
  gender?: string | null
  actorId: string
  actorRole: IdentityRole | null
  providers: AppProviders
}): Promise<StaffResponse> {
  assertAdminAccess(params.actorRole)

  const existing = await params.providers.domainStore.getStaffProfile(params.userId)
  if (!existing) throw AppError.notFound('Staff profile')
  if (
    params.actorRole === 'school_admin' &&
    (existing.role === 'platform_admin' ||
      (await params.providers.domainStore.getUserRoles(params.userId)).includes('platform_admin'))
  ) {
    throw AppError.forbidden()
  }

  if (params.actorRole === 'school_admin') {
    if (params.role === 'platform_admin' || params.roles?.includes('platform_admin')) {
      throw AppError.forbidden()
    }
  }

  const rolesToCheck = [...(params.role ? [params.role] : []), ...(params.roles ?? [])]
  await assertRolesExistAndActive(params.providers, rolesToCheck)

  let assignedRoles: string[] | undefined
  if (params.role !== undefined || params.roles !== undefined) {
    const primaryRole = params.role ?? existing.role
    if (!primaryRole) throw AppError.validationError('Staff primary role is required.')
    if (!params.providers.identityProvider.assignRoles) {
      throw AppError.internal('Identity provider role assignment is not configured.')
    }
    assignedRoles = [...new Set([primaryRole, ...(params.roles ?? [])])]
    await params.providers.identityProvider.assignRoles(params.userId, assignedRoles)
  }

  const affectsSessions =
    params.lifecycleStatus !== undefined || params.role !== undefined || params.roles !== undefined
  const revokeSessions = affectsSessions
    ? params.providers.identityProvider.revokeUserSessions?.bind(params.providers.identityProvider)
    : undefined
  if (affectsSessions && !revokeSessions) {
    throw AppError.internal('Identity provider session revocation is not configured.')
  }
  const restrictsAccess =
    params.lifecycleStatus !== undefined && params.lifecycleStatus !== 'approved'
  // Restrict access before contacting Logto; re-enable only after revocation succeeds.
  if (!restrictsAccess) await revokeSessions?.(params.userId)

  const updated = await params.providers.domainStore.updateStaffProfile(params.userId, {
    fullName: params.fullName,
    role: params.role,
    roles: assignedRoles,
    lifecycleStatus: params.lifecycleStatus,
    gender: params.gender,
  })
  if (restrictsAccess) await revokeSessions?.(params.userId)

  await params.providers.domainStore.insertAuditLog({
    actor_id: params.actorId,
    action: 'update_staff',
    entity_type: 'profile',
    entity_id: params.userId,
    details: {
      user_id: params.userId,
      role: updated.role,
      lifecycle_status: updated.lifecycle_status,
      full_name: updated.full_name,
    },
  })

  const roles = await params.providers.domainStore.getUserRoles(params.userId)
  const effectivePermissions = await params.providers.domainStore.getUserEffectivePermissions(
    params.userId,
  )

  return {
    ...updated,
    roles,
    effective_permissions: effectivePermissions,
  }
}

export async function requestStaffPasswordReset(params: {
  userId: string
  email?: string
  actorId: string
  actorRole: IdentityRole | null
  providers: AppProviders
}): Promise<{ success: boolean; message: string }> {
  assertAdminAccess(params.actorRole)

  const staff = await params.providers.domainStore.getUserProfile(params.userId)
  const targetEmail = params.email ?? staff.email
  if (!targetEmail) {
    throw AppError.validationError('Staff profile has no associated email.')
  }

  await params.providers.identityProvider.requestPasswordResetEmail?.(targetEmail)

  await params.providers.domainStore.insertAuditLog({
    actor_id: params.actorId,
    action: 'request_staff_password_reset',
    entity_type: 'profile',
    entity_id: params.userId,
    details: {
      user_id: params.userId,
      email: targetEmail,
      requested_by: params.actorId,
    },
  })

  return {
    success: true,
    message: 'Password recovery email initiated.',
  }
}

export async function getStaffEffectivePermissions(params: {
  userId: string
  actorRole: IdentityRole | null
  providers: AppProviders
}): Promise<EffectivePermissionsResponse> {
  assertAdminAccess(params.actorRole)

  const roles = await params.providers.domainStore.getUserRoles(params.userId)
  const permissions = await params.providers.domainStore.getUserEffectivePermissions(params.userId)

  return {
    user_id: params.userId,
    roles,
    permissions,
  }
}
